// Writes the contract ABIs for the app: node contracts/export-abi.mjs (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
const abi = (name, file = name) => JSON.stringify(JSON.parse(readFileSync(new URL(`./out/${file}.sol/${name}.json`, import.meta.url))).abi);
const out = [
  ["kaddClubAbi", "KaddClub"],
  ["kaddClubFactoryAbi", "KaddClubFactory"],
  ["kaddVenueAbi", "KaddVenue", "KaddVenue"],
  ["kaddPoolAbi", "KaddPool", "KaddVenue"],
  ["testUsdcAbi", "TestUSDC", "KaddVenue"],
  ["mirrorTokenAbi", "MirrorToken", "KaddVenue"],
  ["kaddStrategiesAbi", "KaddStrategies"],
].map(([v, name, file]) => `export const ${v} = ${abi(name, file)} as const;\n`);
writeFileSync(new URL("../kadd/src/lib/abi.ts", import.meta.url), `// Generated by contracts/export-abi.mjs. Do not edit by hand.\n${out.join("\n")}`);
