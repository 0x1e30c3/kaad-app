// Writes the club ABIs for the app: node contracts/export-abi.mjs (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
const abi = (name) => JSON.stringify(JSON.parse(readFileSync(new URL(`./out/${name}.sol/${name}.json`, import.meta.url))).abi);
writeFileSync(
  new URL("../kadd/src/lib/abi.ts", import.meta.url),
  `// Generated by contracts/export-abi.mjs. Do not edit by hand.\nexport const kaddClubAbi = ${abi("KaddClub")} as const;\n\nexport const kaddClubFactoryAbi = ${abi("KaddClubFactory")} as const;\n`,
);
